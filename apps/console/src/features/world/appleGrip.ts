export function appleVisual(frame: AppleFrame, t: number) {
  if (!frame.motion) return { stand: frame.stand, holder: frame.holder };
  const { n, stand, startedAt } = frame.motion;
  const spec = APPLE_STANDS[stand];
  const afterContact = t >= startedAt + spec.contact;
  return { stand, holder: afterContact === (spec.verb === "grab") ? n : null };
}

export function appleMotion(frame: AppleFrame | undefined, n: number, t: number) {
  const run = frame?.motion;
  if (!run || run.n !== n || t < run.startedAt) return null;
  const spec = APPLE_STANDS[run.stand];
  const curve = spec.verb === "grab" ? pickupGround : placementGround;
  const time = t - run.startedAt;
  const i = Math.min(time * 24, curve.length - 1);
  const lower = Math.floor(i);
  const ground = curve[lower] + (curve[Math.ceil(i)] - curve[lower]) * (i - lower);
  return { clip: spec.clip, time, ground };
}
