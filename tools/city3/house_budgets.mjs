#!/usr/bin/env bun
// Rewrite the placed-house section of apps/console/tests/asset-budgets.ts from the house GLBs on disk (one entry per shared GLB, x1.25 headroom).
// Run after tools/city3/houses.sh. Houses are heavy on purpose (user, 2026-11-23/24: high-poly houses, our own caps do not matter for looks).
//   bun tools/city3/house_budgets.mjs
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";

const H = "apps/console/public/assets/houses", F = "apps/console/tests/asset-budgets.ts";
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const n = (v) => Math.round(v).toLocaleString("en-US").replace(/,/g, "_");
let out = "  // Placed prebuilt houses (generated by tools/city3/house_budgets.mjs from houses.sh output), one entry per shared GLB however many lots use it, x1.25 headroom.\n  // High-poly on purpose (user, 2026-11-23); textures capped at 2048 px by slim_textures.py.\n";
for (const f of readdirSync(H).filter((f) => f.endsWith(".glb") && !f.endsWith(".col.glb") && !f.endsWith(".far.glb")).sort()) {
  const doc = await io.read(`${H}/${f}`);
  let tris = 0;
  for (const m of doc.getRoot().listMeshes()) for (const p of m.listPrimitives()) tris += (p.getIndices()?.getCount() ?? p.getAttribute("POSITION").getCount()) / 3;
  const g = statSync(`${H}/${f}`).size, c = statSync(`${H}/${f.replace(/\.glb$/, ".col.glb")}`).size;
  out += `  "/assets/houses/${f}": {\n    measured: { glbBytes: ${n(g)}, collisionBytes: ${n(c)}, triangles: ${n(tris)} },\n    budget: { glbBytes: ${n(g * 1.25)}, collisionBytes: ${n(Math.max(2000, c * 1.4))}, triangles: ${n(tris * 1.25)} },\n  },\n`;
}
const s = readFileSync(F, "utf8"), a = s.indexOf("  // Placed prebuilt houses"), b = s.indexOf("};\n\n/** All districts");
if (a < 0 || b < 0) throw new Error("house section markers not found in " + F);
writeFileSync(F, s.slice(0, a) + out + s.slice(b));
console.log("house budgets:", readdirSync(H).filter((f) => f.endsWith(".glb") && !f.endsWith(".col.glb") && !f.endsWith(".far.glb")).length);
