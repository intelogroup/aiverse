#!/usr/bin/env bun
// Rewrite the placed-house section of apps/console/tests/asset-budgets.ts from the house GLBs on disk (one entry per shared GLB, x1.25 headroom).
// Run after tools/city3/houses.sh. Houses are heavy on purpose (user, 2026-11-23/24: high-poly houses, our own caps do not matter for looks).
//   bun tools/city3/house_budgets.mjs
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { MeshoptDecoder } from "meshoptimizer";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";

const H = "apps/console/public/assets/houses", F = "apps/console/tests/asset-budgets.ts";
// Absolute ceilings. The generated budget is measured x1.25, which only detects *regression*:
// it re-bases onto whatever was just built, so a runaway house can never fail its own gate
// (cabin-y90.glb ships 766,467 triangles for one log cabin and passes by construction). These
// are the ceiling that makes the row mean something; move them only in a deliberate PR.
// collisionBytes was 20 KB for closed shells; a walk-in house (place_house.mjs --colboxes) carries its measured walls, furniture and
// floor as ~470 boxes in one mesh, 80 KB per yaw, and the row sums every yaw's file (american.glb: y0 + y270 = 160 KB)
const CEILING = { glbBytes: 26_000_000, collisionBytes: 200_000, triangles: 900_000 };
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ "meshopt.decoder": MeshoptDecoder });
await MeshoptDecoder.ready;   // placed houses ship EXT_meshopt_compression; without the decoder io.read throws
const n = (v) => Math.round(v).toLocaleString("en-US").replace(/,/g, "_");
// A shared house GLB can be used by several lots that each carry their OWN collision file
// (american-y0.glb is the mesh for house-american-1 and house-ring-25-0, but house-ring-35-1
// ships american-ring-35-1.col.glb). The test checks every district's collisionUrl against the
// row for its url, so budget the LARGEST collision any of them actually loads, not just the
// same-named sibling -- otherwise the row under-budgets and the gate fails on a file it never saw.
const man = JSON.parse(readFileSync("apps/console/public/assets/districts.json", "utf8"));
const colByUrl = new Map();
for (const d of man.districts) {
  if (!d.url?.startsWith("/assets/houses/")) continue;
  if (!colByUrl.has(d.url)) colByUrl.set(d.url, new Set());
  if (d.collisionUrl) colByUrl.get(d.url).add(d.collisionUrl);
}
const sizeOfUrl = (u) => { try { return statSync(`apps/console/public${u}`).size; } catch { return 0; } };
let out = "  // Placed prebuilt houses (generated by tools/city3/house_budgets.mjs from houses.sh output), one entry per shared GLB however many lots use it, x1.25 headroom.\n  // High-poly on purpose (user, 2026-11-23); textures capped at 2048 px by slim_textures.py.\n";
for (const f of readdirSync(H).filter((f) => f.endsWith(".glb") && !f.endsWith(".col.glb") && !f.endsWith(".far.glb")).sort()) {
  const doc = await io.read(`${H}/${f}`);
  let tris = 0;
  for (const m of doc.getRoot().listMeshes()) for (const p of m.listPrimitives()) tris += (p.getIndices()?.getCount() ?? p.getAttribute("POSITION").getCount()) / 3;
  const g = statSync(`${H}/${f}`).size;
  // asset-budget.test.ts sums the distinct collisionUrls of every lot using this GLB
  // (Set dedupes), so mirror that exactly; fall back to the same-named sibling when the
  // manifest names none.
  const cols = [...(colByUrl.get(`/assets/houses/${f}`) ?? [])];
  let c = cols.reduce((sum, u) => sum + sizeOfUrl(u), 0);
  if (!cols.length) { try { c = statSync(`${H}/${f.replace(/\.glb$/, ".col.glb")}`).size; } catch { c = 0; } }
  const cap = (v, ceil) => Math.round(Math.min(v, ceil));
  if (g > CEILING.glbBytes || tris > CEILING.triangles || c > CEILING.collisionBytes) {
    console.warn(`  OVER CEILING: ${f} (${(g / 1e6).toFixed(1)} MB, ${Math.round(tris)} tris) — the row will fail the gate until it is slimmed or the ceiling is raised deliberately`);
  }
  out += `  "/assets/houses/${f}": {\n    measured: { glbBytes: ${n(g)}, collisionBytes: ${n(c)}, triangles: ${n(tris)} },\n    budget: { glbBytes: ${n(cap(g * 1.25, CEILING.glbBytes))}, collisionBytes: ${n(cap(Math.max(2000, c * 1.4), CEILING.collisionBytes))}, triangles: ${n(cap(tris * 1.25, CEILING.triangles))} },\n  },\n`;
}
const s = readFileSync(F, "utf8"), a = s.indexOf("  // Placed prebuilt houses"), b = s.indexOf("};\n\n/** All districts");
if (a < 0 || b < 0) throw new Error("house section markers not found in " + F);
writeFileSync(F, s.slice(0, a) + out + s.slice(b));
console.log("house budgets:", readdirSync(H).filter((f) => f.endsWith(".glb") && !f.endsWith(".col.glb") && !f.endsWith(".far.glb")).length);
