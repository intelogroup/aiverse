#!/usr/bin/env python3
"""Emit houses.sh lines that put prebuilt houses on the 18 edge-ring blocks, facing the inner street.

Per block: two houses along its street side (one, centred, when two would not keep 4 m between them), each set back 3 m from the block's inner
rect, lifted 0.05 m over the landscape grass. Models rotate through a per-side list so a model needs at most two yaws (one shared GLB per yaw).
Footprints: local width w (x) and depth d (z, front = +z) after scale.
  python3 tools/city3/ring_houses.py >> tools/city3/houses.sh      (then bash houses.sh, bridge_clear_footprints.py, house_budgets.mjs)
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
M = {   # model: (scale, w, d, extra args)
    "victorian-green": (7, 9.1, 11.2, ""), "kruglov-house": (0.014, 12.9, 18.1, ""), "small-brick": (0.03, 9.3, 15.0, ""),
    "suburban-blue": (1, 12.5, 10.9, ""), "medieval-rx": (1, 10.7, 10.8, ""), "residence-wsg": (0.01, 13.4, 14.6, ""),
    "suburban-bogdan": (1, 16.4, 15.6, ""), "cozy-cottage": (1, 8.6, 22.2, ""), "american-house": (1, 19.5, 15.5, ""),
}
ASSET = {"american-house": "american"}   # existing shared asset names
SIDES = {   # side: (yaw, models in rotation)
    "W": (90, ["victorian-green", "kruglov-house", "small-brick", "suburban-blue", "medieval-rx"]),
    "E": (270, ["residence-wsg", "suburban-bogdan", "cozy-cottage", "american-house", "victorian-green"]),
    "N": (180, ["kruglov-house", "suburban-bogdan", "medieval-rx", "small-brick", "residence-wsg"]),
    "S": (0, ["cozy-cottage", "suburban-blue", "american-house"]),
}
SETBACK, GAP, LIFT = 3.0, 4.0, 0.05


def side_of(i, j):
    return "W" if i == 0 else "E" if i == 5 else "N" if j == 0 else "S"


def placements(blocks):
    out, k = [], {s: 0 for s in SIDES}
    for b in blocks:
        if b["kind"] != "edge":
            continue
        x0, z0, x1, z1 = b["inner"][0], -b["inner"][3], b["inner"][2], -b["inner"][1]   # plan -> GLB (z = -plan y)
        s = side_of(b["i"], b["j"]); yaw, models = SIDES[s]
        along_x = s in "NS"
        a0, a1 = (x0, x1) if along_x else (z0, z1)
        L = a1 - a0
        picks = [models[k[s] % len(models)], models[(k[s] + 1) % len(models)]]
        widths = [M[m][1] for m in picks]
        slots = [(a0 + L / 4, picks[0]), (a0 + 3 * L / 4, picks[1])] if L / 2 >= (widths[0] + widths[1]) / 2 + GAP else [((a0 + a1) / 2, picks[0])]
        k[s] += len(slots)
        for n, (a, m) in enumerate(slots):
            sc, w, d, extra = M[m]
            if s == "W":
                x, z = x1 - SETBACK - d / 2, a
            elif s == "E":
                x, z = x0 + SETBACK + d / 2, a
            elif s == "N":
                x, z = a, z0 + SETBACK + d / 2
            else:
                x, z = a, z1 - SETBACK - d / 2
            hid = f"ring-{b['i']}{b['j']}-{n}"
            out.append(f"P {m:<18} {hid:<14} {x:7.1f} {z:7.1f} {yaw:4d} --asset={ASSET.get(m, m)} --scale={sc} --lift={LIFT} --door=none {extra}".rstrip())
    return out


if __name__ == "__main__":
    lines = placements(json.load(open(os.path.join(HERE, "plan.json")))["blocks"])
    yaws = {}
    for l in lines:
        yaws.setdefault(l.split()[1], set()).add(l.split()[5])
    assert all(len(v) <= 2 for v in yaws.values()), yaws
    print("# edge ring (generated by ring_houses.py)"); print("\n".join(lines))
