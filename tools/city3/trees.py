"""Dense procedural trees for the Bazaar (runs inside Blender, imported by build_city.py).

A variant = tapered-tube trunk + 2 branch levels with a bark texture (Poly Haven bark_brown_02, CC0) + a few hundred V-folded
leaf-cluster cards textured from tex_trees/tree_leaves.png (generated by trees_tex.py, nothing to license). Cards carry spherical
crown normals (smooth, volumetric shading instead of flat cards) and a baked vertex-colour tint (AO: dark centre / lit rim, per-card hue).
One mesh with two materials per variant ("tree_bark", "tree_foliage"); placements are linked duplicates under an Empty
`inst_tree_<variant>` so the exporter writes EXT_mesh_gpu_instancing (one mesh, ~20 nodes folded into one).
"""
