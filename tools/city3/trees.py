def _mats():
    if "tree_foliage" in bpy.data.materials: return bpy.data.materials["tree_bark"], bpy.data.materials["tree_foliage"]
    mb = bpy.data.materials.new("tree_bark"); mb.use_nodes = True; nt = mb.node_tree
    for n in list(nt.nodes):
        if n.type not in ("OUTPUT_MATERIAL", "BSDF_PRINCIPLED"): nt.nodes.remove(n)
    b = nt.nodes["Principled BSDF"]; b.inputs["Roughness"].default_value = 0.92
    t = nt.nodes.new("ShaderNodeTexImage"); t.image = bpy.data.images.load(os.path.join(TT, "tree_bark.jpg")); t.extension = "REPEAT"
    nt.links.new(t.outputs["Color"], b.inputs["Base Color"]); mb.use_backface_culling = True
    mf = bpy.data.materials.new("tree_foliage"); mf.use_nodes = True; nt = mf.node_tree
    for n in list(nt.nodes):
        if n.type not in ("OUTPUT_MATERIAL", "BSDF_PRINCIPLED"): nt.nodes.remove(n)
    b = nt.nodes["Principled BSDF"]; b.inputs["Roughness"].default_value = 0.78
    t = nt.nodes.new("ShaderNodeTexImage"); t.image = bpy.data.images.load(os.path.join(TT, "tree_leaves.png")); t.extension = "CLIP"
    vc = nt.nodes.new("ShaderNodeVertexColor"); vc.layer_name = "Col"
    mx = nt.nodes.new("ShaderNodeMix"); mx.data_type = "RGBA"; mx.blend_type = "MULTIPLY"; mx.inputs[0].default_value = 1.0
    nt.links.new(t.outputs["Color"], mx.inputs[6]); nt.links.new(vc.outputs["Color"], mx.inputs[7]); nt.links.new(mx.outputs[2], b.inputs["Base Color"])
    r = nt.nodes.new("ShaderNodeMath"); r.operation = "ROUND"; nt.links.new(t.outputs["Alpha"], r.inputs[0]); nt.links.new(r.outputs[0], b.inputs["Alpha"])
    mf.use_backface_culling = False
    for a, v in (("surface_render_method", "DITHERED"), ("blend_method", "CLIP")):
        try: setattr(mf, a, v)
        except Exception: pass
    return mb, mf


class Acc:
    def __init__(s): s.v = []; s.f = []; s.uv = []; s.n = []; s.col = []; s.mi = []
    def vert(s, p, n, col): s.v.append(tuple(p)); s.n.append(tuple(n)); s.col.append(col); return len(s.v) - 1


def _frame(d):
    d = d.normalized(); a = Vector((1, 0, 0)) if abs(d.x) < 0.9 else Vector((0, 1, 0)); u = d.cross(a).normalized(); return u, d.cross(u).normalized()


def tube(acc, pts, radii, sides, uvrep, v0=0.0, tint=1.0):
    """Tapered tube through `pts` (Vectors) with smooth radial normals; bark UV: u repeats `uvrep` times round, v = metres along."""
    rings = []; d_prev = None; v = v0
    for i, p in enumerate(pts):
        d = (pts[min(i + 1, len(pts) - 1)] - pts[max(i - 1, 0)]); d = d.normalized() if d.length > 1e-6 else UP
        if i == 0: u, w = _frame(d)
        else:                                                              # parallel transport the frame
            u = (u - d * u.dot(d)); u = u.normalized() if u.length > 1e-6 else _frame(d)[0]; w = d.cross(u)
        if i: v += (p - pts[i - 1]).length
        ring = []
        for k in range(sides + 1):
            a = 2 * math.pi * k / sides; nrm = u * math.cos(a) + w * math.sin(a)
            ring.append((acc.vert(p + nrm * radii[i], nrm, (1, 1, 1, 1)), k / sides * uvrep, v))
        rings.append(ring)
    for i in range(len(rings) - 1):
        for k in range(sides):
            a, b, c, d = rings[i][k], rings[i][k + 1], rings[i + 1][k + 1], rings[i + 1][k]
            acc.f.append((a[0], b[0], c[0], d[0])); acc.uv.append(((a[1], a[2]), (b[1], b[2]), (c[1], c[2]), (d[1], d[2]))); acc.mi.append(0)
    # cap the tip
    return rings


def path(r, p0, d0, length, nseg, bend_up, wob):
    pts = [p0]; d = d0.normalized(); step = length / nseg
    for i in range(nseg):
        d = (d + UP * bend_up / nseg + Vector((r.gauss(0, wob), r.gauss(0, wob), r.gauss(0, wob * 0.5)))).normalized()
        pts.append(pts[-1] + d * step)
    return pts


def build(name, P):
    r = random.Random(P["seed"]); bark = Acc(); leaf = Acc()
    H, rx, rz, zc, ht, r0 = P["H"], P["rx"], P["rz"], P["zc"], P["ht"], P["r0"]; cc = Vector((0, 0, zc))
    # --- trunk / leader: slightly sinuous, flared foot, tapering into the crown ---
    top = H * 0.86; nseg = 9; lean = Vector((r.gauss(0, 0.25), r.gauss(0, 0.25), 0)) * (0.5 + P["wob"] * 3)
    lp = path(r, Vector((0, 0, -0.12)), Vector((lean.x * 0.15, lean.y * 0.15, 1.0)), top + 0.12, nseg, 0.0, P["wob"] * 0.5)
    rad = []
    for i, p in enumerate(lp):
        t = i / nseg; z = p.z; flare = 1 + 0.55 * max(0.0, 1 - (z + 0.12) / 0.7) ** 2
        rad.append(max(0.035, (r0 * (1 - 0.72 * t ** 0.8)) * flare))
    tube(bark, lp, rad, 10, max(1, round(2 * math.pi * r0 / 0.9)))
    root = [Vector((0, 0, 0))]
    def on_leader(t):
        f = t * nseg; i = min(int(f), nseg - 1); a = f - i; return lp[i].lerp(lp[i + 1], a), rad[i] * (1 - a) + rad[i + 1] * a
    anchors = []                                                                 # (point, outward-weight) for leaf cards
    ph = r.uniform(0, 2 * math.pi)
    for bi in range(P["n_br"]):
        t = (ht / top) + (0.97 - ht / top) * (bi + r.uniform(-0.1, 0.1) + 0.4) / (P["n_br"] + 0.4); t = min(0.97, max(0.1, t))
        p0, rr0 = on_leader(t); z = p0.z
        rho = rx * math.sqrt(max(0.04, 1 - ((z - zc) / rz) ** 2)); a = ph + bi * 2.399 + r.uniform(-0.25, 0.25)
        el = P["el"] * r.uniform(0.8, 1.15) + (0.35 if z > zc else 0.0)
        d0 = Vector((math.cos(a) * math.cos(el), math.sin(a) * math.cos(el), math.sin(el)))
        L = max(1.0, rho * 1.0 / max(0.45, math.cos(el * 0.8))); ns = 5
        bp = path(r, p0 + d0 * 0.0, d0, L, ns, 0.25, P["wob"] * 0.6)
        inside = lambda q: ((q.x / rx) ** 2 + (q.y / rx) ** 2 + ((q.z - zc) / rz) ** 2) < 0.9
        k_ = len(bp)
        for i_ in range(2, len(bp)):
            if not inside(bp[i_]): k_ = i_; break
        bp = bp[:max(3, k_)]; ns = len(bp) - 1
        rb = [max(0.03, min(rr0 * 0.62, 0.2) * (1 - 0.82 * i / ns)) for i in range(ns + 1)]
        tube(bark, bp, rb, 6, 1)
        anchors.append((bp[-1], 1.0)); anchors.append((bp[-2], 0.8))
        for si in range(3):                                                      # second-level branches
            t2 = 0.35 + 0.22 * si + r.uniform(-0.05, 0.05); i2 = min(int(t2 * ns), ns - 1); q0 = bp[i2].lerp(bp[i2 + 1], t2 * ns - i2)
            dd = (bp[i2 + 1] - bp[i2]).normalized(); u, w = _frame(dd); az = r.uniform(0, 2 * math.pi)
            d2 = (dd * 0.8 + (u * math.cos(az) + w * math.sin(az)) * 0.7 + UP * 0.25).normalized()
            L2 = L * r.uniform(0.32, 0.5); sp = path(r, q0, d2, L2, 3, 0.2, P["wob"] * 0.5)
            rs = rb[i2] * 0.6; tube(bark, sp, [max(0.02, rs * (1 - 0.8 * i / 3)) for i in range(4)], 5, 1)
            for q in sp[1:]:
                if inside(q): anchors.append((q, 0.9))
    # --- leaf-cluster cards ---
    col_i, row_i = P["tile"] % 2, P["tile"] // 2; ud, vd = 0.5, 0.5
    u0, v0 = col_i * 0.5 + 0.004, 1 - (row_i + 1) * 0.5 + 0.004; u1, v1 = u0 + ud - 0.008, v0 + vd - 0.008
    tint = P["tint"]; NB = int(P["n_cards"] * 0.72); NF = P["n_cards"] - NB
    pts = []
    for i in range(NB):                                                          # on the branch tips
        a, _w = anchors[i % len(anchors)]; off = Vector((r.gauss(0, 1), r.gauss(0, 1), r.gauss(0, 0.8))) * P["hs"] * 1.05
        pts.append(a + off)
    lobes = [(Vector((r.gauss(0, 1), r.gauss(0, 1), r.gauss(0, 0.6))).normalized(), r.uniform(0.25, 0.6)) for _ in range(7)]
    for i in range(NF):                                                          # fill the ellipsoid, biased to the shell
        while True:
            dv = Vector((r.gauss(0, 1), r.gauss(0, 1), r.gauss(0, 1)))
            if dv.length > 1e-3: break
        dv.normalize(); rr = (0.3 + 0.7 * r.random() ** 0.45) * (0.88 + sum(w * max(0.0, dv.dot(v)) ** 2 for v, w in lobes))
        q = cc + Vector((dv.x * rx * rr, dv.y * rx * rr, dv.z * rz * rr))
        if q.z < ht * 0.9 + 0.2: q.z = ht * 0.9 + 0.2 + r.random() * 0.3
        pts.append(q)
    cl = []
    for c in pts:
        q = Vector((c.x / rx, c.y / rx, (c.z - zc) / rz)); m = q.length
        if m > 1.0: c = Vector((q.x / m * rx, q.y / m * rx, zc + q.z / m * rz))
        cl.append(c)
    pts = cl
    for c in pts:
        rel = Vector(((c.x) / rx, (c.y) / rx, (c.z - zc) / rz)); rn = min(1.3, rel.length)
        n = Vector((rel.x, rel.y, rel.z * 0.8)); n = n.normalized() if n.length > 1e-3 else UP
        n = (n + Vector((r.gauss(0, .7), r.gauss(0, .7), r.gauss(0, .6)))).normalized()
        u, w = _frame(n); ph2 = r.uniform(0, 2 * math.pi); u, w = u * math.cos(ph2) + w * math.sin(ph2), w * math.cos(ph2) - u * math.sin(ph2)
        hs = P["hs"] * 1.25 * r.uniform(0.8, 1.2)
        k = (0.68 + 0.42 * min(1.0, rn) ** 1.2 + 0.14 * max(-1, min(1, rel.z)) + r.gauss(0, 0.07)); k = max(0.35, k)
        j = (1 + r.gauss(0, 0.05), 1 + r.gauss(0, 0.04), 1 + r.gauss(0, 0.06)); colr = (min(1.4, tint[0] * k * j[0]), min(1.4, tint[1] * k * j[1]), min(1.4, tint[2] * k * j[2]), 1.0)
        fold = 0.18 * hs; mir = r.random() < 0.5
        P_ = lambda su, sw, up_: c + u * (su * hs) + w * (sw * hs) + n * up_
        ids = []
        for (su, sw, up_, uu, vv) in ((-1, -1, 0, 0, 0), (0, -1, fold, 0.5, 0), (1, -1, 0, 1, 0), (1, 1, 0, 1, 1), (0, 1, fold, 0.5, 1), (-1, 1, 0, 0, 1)):
            p = P_(su, sw, up_); nn = Vector(((p.x) / rx, (p.y) / rx, (p.z - zc) / rz * 0.9)); nn = nn.normalized() if nn.length > 1e-3 else n
            if mir: uu = 1 - uu
            ids.append((leaf.vert(p, nn, colr), u0 + (u1 - u0) * uu, v0 + (v1 - v0) * vv))
        for qd in ((0, 1, 4, 5), (1, 2, 3, 4)):
            leaf.f.append(tuple(ids[q][0] for q in qd)); leaf.uv.append(tuple((ids[q][1], ids[q][2]) for q in qd)); leaf.mi.append(1)
    # --- one mesh, two material slots ---
    mb_, mf_ = _mats(); V = bark.v + leaf.v; off = len(bark.v)
    F = bark.f + [tuple(i + off for i in f) for f in leaf.f]; UVs = bark.uv + leaf.uv; MI = bark.mi + leaf.mi; NR = bark.n + leaf.n; COL = bark.col + leaf.col
    me = bpy.data.meshes.new(f"tree_{name}"); me.from_pydata(V, [], F); me.update()
    uvl = me.uv_layers.new(name="UVMap")
    for pi, poly in enumerate(me.polygons):
        for li, loop in enumerate(poly.loop_indices): uvl.data[loop].uv = UVs[pi][li]
    me.materials.append(mb_); me.materials.append(mf_); me.polygons.foreach_set("material_index", MI)
    me.polygons.foreach_set("use_smooth", [True] * len(me.polygons))
    me.normals_split_custom_set_from_vertices([tuple(n) for n in NR])
    ca = me.color_attributes.new("Col", "FLOAT_COLOR", "POINT")
    for i, c in enumerate(COL): ca.data[i].color = c
    tris = sum(len(p.vertices) - 2 for p in me.polygons)
    o = bpy.data.objects.new(f"LIB_treemaster_{name}", me); bpy.context.scene.collection.objects.link(o)   # LIB_ prefix: skipped by the city export, deleted before the library export; only its mesh is shared
    emp = bpy.data.objects.new(f"inst_tree_{name}", None); bpy.context.scene.collection.objects.link(emp)
    LIB[name] = dict(obj=o, empty=emp, tris=tris, n=0, cards=len(pts))
    print(f"TREE {name}: {tris} tris, {len(pts)} cards, {len(V)} verts")


def place(name, x, y, z, rot, s, sxy=1.0):
    if not LIB: init()
    L = LIB[name]; o = L["obj"].copy(); o.data = L["obj"].data; o.name = f"tree_{name}"; o.location = (x, y, z); o.rotation_euler = (0, 0, rot)
    o.scale = (s * sxy, s / sxy, s); o.parent = L["empty"]; bpy.context.scene.collection.objects.link(o); L["n"] += 1
    return o


def init():
    for k, P in VARIANTS.items(): build(k, P)
